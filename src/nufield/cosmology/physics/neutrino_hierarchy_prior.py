"""Prior transforms and support checks for cosmological neutrino-mass inference.

The prior is part of the scientific result: a posterior near a mass boundary can depend strongly on
whether the sampling coordinate is the sum, a lightest eigenmass, or a logarithmic transform. These
helpers keep the convention explicit and reject impossible hierarchy support. They do not encode a
universal best prior; choose one based on the stated scientific question.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np

from nufield.cosmology.physics.neutrino_mass_observables import (
    OscillationReference,
    minimum_mass_sum_ev,
    solve_mass_eigenvalues,
)

Hierarchy = Literal["normal", "inverted"]
PriorKind = Literal["uniform_sum", "uniform_lightest", "log_lightest"]


@dataclass(frozen=True, slots=True)
class NeutrinoMassPrior:
    hierarchy: Hierarchy
    lower_sum_ev: float
    upper_sum_ev: float
    kind: PriorKind = "uniform_sum"
    oscillation_reference: OscillationReference = OscillationReference()

    def __post_init__(self) -> None:
        if self.hierarchy not in {"normal", "inverted"}:
            raise ValueError("hierarchy must be normal or inverted")
        if self.kind not in {"uniform_sum", "uniform_lightest", "log_lightest"}:
            raise ValueError("unsupported prior kind")
        floor = minimum_mass_sum_ev(self.hierarchy, inputs=self.oscillation_reference)
        if (
            not np.isfinite(self.lower_sum_ev + self.upper_sum_ev)
            or self.upper_sum_ev <= self.lower_sum_ev
        ):
            raise ValueError("mass prior bounds must be finite and ordered")
        if self.lower_sum_ev < floor - 1e-12:
            raise ValueError(f"lower mass-sum bound is below hierarchy minimum {floor:.8g} eV")
        if self.kind == "log_lightest" and self.lower_sum_ev <= floor:
            raise ValueError(
                "log-lightest prior requires a lower sum bound strictly above the hierarchy floor"
            )

    @property
    def minimum_allowed_sum_ev(self) -> float:
        return minimum_mass_sum_ev(self.hierarchy, inputs=self.oscillation_reference)

    def transform_unit_cube(self, u: np.ndarray) -> np.ndarray:
        """Map values in [0,1] to neutrino mass sums under the declared sampling coordinate."""
        x = np.asarray(u, float)
        if np.any(~np.isfinite(x)) or np.any((x < 0) | (x > 1)):
            raise ValueError("unit-cube coordinates must lie in [0,1]")
        if self.kind == "uniform_sum":
            return self.lower_sum_ev + x * (self.upper_sum_ev - self.lower_sum_ev)
        light_lo = _lightest_from_sum(self.lower_sum_ev, self.hierarchy, self.oscillation_reference)
        light_hi = _lightest_from_sum(self.upper_sum_ev, self.hierarchy, self.oscillation_reference)
        if self.kind == "uniform_lightest":
            m0 = light_lo + x * (light_hi - light_lo)
        else:
            m0 = np.exp(np.log(light_lo) + x * (np.log(light_hi) - np.log(light_lo)))
        # Convert each lightest mass to the hierarchy-consistent sum. The vector loop is deliberate
        # because the mass eigenvalues are obtained from a robust scalar root solve.
        return np.asarray(
            [
                sum(_masses(float(v), self.hierarchy, self.oscillation_reference))
                for v in np.ravel(m0)
            ]
        ).reshape(x.shape)

    def to_dict(self) -> dict[str, object]:
        return {
            "hierarchy": self.hierarchy,
            "lower_sum_ev": self.lower_sum_ev,
            "upper_sum_ev": self.upper_sum_ev,
            "kind": self.kind,
            "minimum_allowed_sum_ev": self.minimum_allowed_sum_ev,
            "oscillation_reference": self.oscillation_reference.to_dict(),
            "warning": "A uniform prior in one mass coordinate is not uniform in another coordinate.",
        }


def _masses(
    lightest: float, hierarchy: Hierarchy, ref: OscillationReference
) -> tuple[float, float, float]:
    # A sum just above the hierarchy minimum must still be mapped robustly. Solve for the total
    # generated by the lightest mass analytically from the same mass-squared convention.
    from nufield.cosmology.physics.neutrino_mass_observables import _eigenmasses_from_lightest

    return _eigenmasses_from_lightest(lightest, hierarchy, ref)


def _lightest_from_sum(total: float, hierarchy: Hierarchy, ref: OscillationReference) -> float:
    masses = solve_mass_eigenvalues(total, hierarchy, inputs=ref)
    # The lightest mass is m1 in normal ordering and m3 in inverted ordering.
    return float(masses[0] if hierarchy == "normal" else masses[2])


def validate_mass_prior_samples(
    samples_sum_ev: np.ndarray, prior: NeutrinoMassPrior
) -> dict[str, float | int | bool]:
    """Audit finite prior samples for support, range, hierarchy-floor violations and endpoints."""
    x = np.asarray(samples_sum_ev, float)
    if x.ndim != 1 or x.size == 0 or np.any(~np.isfinite(x)):
        raise ValueError("samples must be a non-empty finite vector")
    floor = prior.minimum_allowed_sum_ev
    valid = (
        (x >= prior.lower_sum_ev - 1e-12) & (x <= prior.upper_sum_ev + 1e-12) & (x >= floor - 1e-12)
    )
    return {
        "n_samples": int(x.size),
        "valid_fraction": float(np.mean(valid)),
        "below_hierarchy_floor": int(np.count_nonzero(x < floor - 1e-12)),
        "below_prior_minimum": int(np.count_nonzero(x < prior.lower_sum_ev - 1e-12)),
        "above_prior_maximum": int(np.count_nonzero(x > prior.upper_sum_ev + 1e-12)),
        "sample_min_ev": float(x.min()),
        "sample_max_ev": float(x.max()),
        "lower_bound_ev": float(prior.lower_sum_ev),
        "upper_bound_ev": float(prior.upper_sum_ev),
        "hierarchy_minimum_ev": float(floor),
        "support_valid": bool(np.all(valid)),
    }


def draw_neutrino_mass_prior(prior: NeutrinoMassPrior, n: int, *, seed: int = 0) -> np.ndarray:
    """Draw reproducible independent samples using a unit-uniform transform."""
    if n < 1 or seed < 0:
        raise ValueError("n must be positive and seed non-negative")
    return prior.transform_unit_cube(np.random.default_rng(seed).uniform(size=n))


__all__ = ["NeutrinoMassPrior", "validate_mass_prior_samples", "draw_neutrino_mass_prior"]
